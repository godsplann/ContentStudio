// Frame of the n-th (1-based) occurrence of a word, so shots can be keyed to the narration.
export const at = (text: string, n = 1): number => {
  let k = 0;
  for (const w of words) {
    if (w.text.replace(/[.,?!।…]/g, '') === text && ++k === n) return Math.round(w.start * 30);
  }
  throw new Error(`word not found: ${text} #${n}`);
};

